import { _electron as electron } from '@playwright/test';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
const root = await mkdtemp(join(tmpdir(), 'common-ground-desktop-'));
let app;
const env = { ...process.env, COMMON_GROUND_TEST_DATA: join(root, 'library'), CODEX_HOME: join(root, 'codex'), CLAUDE_CONFIG_DIR: join(root, 'claude'), XDG_CONFIG_HOME: join(root, 'config') };
delete env.ELECTRON_RUN_AS_NODE;
const launch = () => electron.launch({ args: ['.', ...(process.platform === 'linux' ? ['--ozone-platform=headless'] : [])], env });
try {
  const repo = join(root, 'project with spaces');
  execFileSync('git', ['init', '-b', 'main', repo]);
  execFileSync('git', ['-C', repo, '-c', 'user.name=Test', '-c', 'user.email=test@example.com', 'commit', '--allow-empty', '-m', 'Initial']);
  await mkdir(join(env.CODEX_HOME, 'sessions'), { recursive: true });
  await writeFile(join(env.CODEX_HOME, 'sessions', 'test.jsonl'), JSON.stringify({ type: 'session_meta', payload: { id: 'session-1', cwd: repo } }) + '\n');
  app = await launch();
  let page = await app.firstWindow();
  await page.waitForFunction(() => !!window.workspace);
  assert.equal((await page.evaluate(() => window.workspace.discover())).added, 1);
  const snapshot = await page.evaluate(() => window.workspace.snapshot());
  assert.equal(snapshot.projects.length, 1); assert.equal(snapshot.sessions.length, 1);
  const id = snapshot.projects[0].id;
  await page.evaluate(id => window.workspace.update(id, { name: 'Saved project', notes: 'Persistent notes', favorite: true }), id);
  assert.equal((await page.evaluate(id => window.workspace.git(id), id)).branch, 'main');
  const tree = join(root, 'parallel tree');
  await app.evaluate(({ dialog }, path) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: path }); }, tree);
  assert.equal(await page.evaluate(id => window.workspace.worktree(id, 'feature/parallel'), id), true);
  assert.equal((await page.evaluate(id => window.workspace.git(id), id)).worktrees.length, 2);
  await app.close();
  app = await launch(); page = await app.firstWindow(); await page.waitForFunction(() => !!window.workspace);
  const restored = await page.evaluate(() => window.workspace.snapshot());
  assert.equal(restored.projects.length, 2);
  assert.ok(restored.projects.some(p => p.name === 'Saved project' && p.notes === 'Persistent notes' && p.favorite));
  await page.evaluate(id => window.workspace.remove(id), id);
  assert.equal((await page.evaluate(() => window.workspace.snapshot())).projects.length, 1);
  execFileSync('git', ['-C', repo, 'status', '--porcelain']);
  console.log('Desktop smoke passed: discovery, history, IPC, Git, worktree creation, persistence, and non-destructive removal.');
} finally { await app?.close(); await rm(root, { recursive: true, force: true }); }
